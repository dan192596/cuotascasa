import {
  buildPaths,
  compareSchedules,
  instantiateTemplate,
  type LoanTerms,
  type Money,
  moneySub,
  parseLocalDate,
  parseMoney,
  parsePaymentDay,
  parseRate,
  percentOf,
  type PrepaymentEvent,
  type Schedule,
} from '@cuotascasa/domain';
import { formatLocalDate, formatMoney } from '../../../ui/format/format.ts';
import type { LandingExampleRow, LandingExampleRows, LandingExampleSummary } from './example-types.ts';

/**
 * Builds the landing example (W8-07) with the domain engine. Only specs import this file: `example-data.spec.ts` checks
 * that the generated modules equal its output and rewrites them with `UPDATE_LANDING_EXAMPLE=1`, so neither the engine
 * nor `ui/` ever enters the landing's graph. Synthetic data: template fha-gt@1 (FHA_GT_V1, 1.00 % + 0.26 %),
 * Q 500,000.00, 240 months, 7.00 % fixed, payment day 15 from 2026-01-15, and a REDUCE_TERM prepayment of Q 50,000.00
 * at installment 60 ([ALG.PREPAY.REDUCE_TERM]).
 */
const PRINCIPAL: Money = parseMoney('500000.00');
const PREPAYMENT: Money = parseMoney('50000.00');
const PREPAY_AT = 60;

function terms(): LoanTerms {
  const template = instantiateTemplate({ id: 'fha-gt', version: 1 });
  return {
    principal: PRINCIPAL,
    termMonths: 240,
    disbursementDate: parseLocalDate('2025-12-15'),
    firstDueDate: parseLocalDate('2026-01-15'),
    paymentDay: parsePaymentDay(15),
    currency: 'GTQ',
    interestRate: parseRate('0.07'),
    insuranceRates: template.insuranceRates.map((line) => line.rate),
    fixedCharges: [],
    roundingProfile: template.roundingProfile,
    rateType: 'FIXED',
  };
}

const q = (value: Money): string => formatMoney(value, 'GTQ');

function rowsOf(schedule: Schedule): LandingExampleRow[] {
  return schedule.rows.map((row) => {
    const balance = row.closingAfterPrepayment;
    const paid = percentOf(moneySub(PRINCIPAL, balance), PRINCIPAL, 1);
    return { k: row.k, balance: q(balance), paidPercent: `${paid} %`, dueDate: formatLocalDate(row.dueDate) };
  });
}

export function buildLandingExample(): { summary: LandingExampleSummary; rows: LandingExampleRows } {
  const loan = terms();
  const base = buildPaths({ terms: loan, realEvents: [], scenarioEvents: null }).original;
  const anchor = base.rows[PREPAY_AT - 1];
  const first = base.rows[0];
  if (anchor === undefined || first === undefined) throw new Error('The example base plan is too short');
  // The event date is the due date of installment 60, so [ALG.EVENTS.ANCHOR] rule 2 applies it after k = 60.
  const event: PrepaymentEvent = {
    type: 'Prepayment',
    id: 'landing-example-prepayment',
    date: anchor.dueDate,
    amount: PREPAYMENT,
    mode: 'REDUCE_TERM',
  };
  const prepaid = buildPaths({ terms: loan, realEvents: [], scenarioEvents: [event] }).scenario;
  if (prepaid === null) throw new Error('The example scenario was not built');
  const metrics = compareSchedules(base, prepaid);
  const rows: LandingExampleRows = { base: rowsOf(base), prepaid: rowsOf(prepaid) };
  const at60 = rows.base[PREPAY_AT - 1];
  if (at60 === undefined) throw new Error('The example has no installment 60');
  return {
    summary: {
      synthetic: true,
      level: q(first.level),
      prepayment: { installment: PREPAY_AT, amount: q(PREPAYMENT) },
      baseCount: base.installmentCount,
      prepaidCount: prepaid.installmentCount,
      monthsSaved: metrics.monthsSaved,
      costSaved: q(metrics.interestSaved),
      at60,
      first: {
        interest: q(first.interest),
        insurance: q(first.insurance),
        capital: q(first.capital),
        total: q(first.total),
      },
    },
    rows,
  };
}

const HEADER = '// Generated by example-data.spec.ts from build-example.ts (UPDATE_LANDING_EXAMPLE=1). Do not edit.\n';

const str = (value: string): string => `'${value}'`;
const rowLiteral = (row: LandingExampleRow): string =>
  `{ k: ${String(row.k)}, balance: ${str(row.balance)}, paidPercent: ${str(row.paidPercent)}, dueDate: ${str(row.dueDate)} }`;

/** The summary module: plain data, with only a type import (it enters the landing's initial graph). */
export function renderSummaryModule(summary: LandingExampleSummary): string {
  const { first, prepayment } = summary;
  return [
    HEADER.trimEnd(),
    "import type { LandingExampleSummary } from './example-types.ts';",
    '',
    'export const LANDING_EXAMPLE_SUMMARY: LandingExampleSummary = {',
    '  synthetic: true,',
    `  level: ${str(summary.level)},`,
    `  prepayment: { installment: ${String(prepayment.installment)}, amount: ${str(prepayment.amount)} },`,
    `  baseCount: ${String(summary.baseCount)},`,
    `  prepaidCount: ${String(summary.prepaidCount)},`,
    `  monthsSaved: ${String(summary.monthsSaved)},`,
    `  costSaved: ${str(summary.costSaved)},`,
    `  at60: ${rowLiteral(summary.at60)},`,
    '  first: {',
    `    interest: ${str(first.interest)},`,
    `    insurance: ${str(first.insurance)},`,
    `    capital: ${str(first.capital)},`,
    `    total: ${str(first.total)},`,
    '  },',
    '};',
    '',
  ].join('\n');
}

/** The rows module: plain data, with only a type import (it lives in the board's lazy chunk). */
export function renderRowsModule(rows: LandingExampleRows): string {
  const list = (items: readonly LandingExampleRow[]): string[] => items.map((row) => `    ${rowLiteral(row)},`);
  return [
    HEADER.trimEnd(),
    "import type { LandingExampleRows } from './example-types.ts';",
    '',
    'export const LANDING_EXAMPLE_ROWS: LandingExampleRows = {',
    '  base: [',
    ...list(rows.base),
    '  ],',
    '  prepaid: [',
    ...list(rows.prepaid),
    '  ],',
    '};',
    '',
  ].join('\n');
}
